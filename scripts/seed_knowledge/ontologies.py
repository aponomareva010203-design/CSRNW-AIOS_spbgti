def C(cid, name, desc, parent="", synonyms=(), attrs=()):
    """Класс онтологии; attrs — пары (id, имя[, тип])."""
    cls = {"id": cid, "name": name, "description": desc}
    if parent:
        cls["parent"] = parent
    if synonyms:
        cls["synonyms"] = list(synonyms)
    if attrs:
        cls["attributes"] = [
            {"id": a[0], "name": a[1], "type": a[2] if len(a) > 2 else "string"}
            for a in attrs
        ]
    return cls


def R(rid, name, dom, rng):
    return {"id": rid, "name": name, "domain_class": dom, "range_class": rng}


def Q(i, question, coverage):
    return {"id": f"cq-{i}", "question": question, "coverage": list(coverage)}



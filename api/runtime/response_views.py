"""Каталог компонентов ответа агента (api/runtime/response_views.py).

Агент не описывает интерфейс — он выбирает компонент из каталога и наполняет
его данными; отрисовкой владеет фронтенд (frontend/js/agent_views.js). Здесь
живёт вторая половина этого соглашения: текст, которым платформа объясняет
модели, какие компоненты есть и когда какой брать.

Зачем отдельный модуль, а не строки в промпте каждого агента. Раньше список
компонентов был вписан в системный промпт каждого шаблона — и по два раза,
в карточке и в узле рассуждения: тридцать четыре копии одного текста на
семнадцать агентов. Следствия были ровно те же, что у методик до recipes.py:

  • новый компонент не доходил до уже созданных агентов вовсе — ни до тех,
    что участники собрали руками, ни до загруженных из шаблонов;
  • участник, правящий инструкцию своего агента словами, легко сносил блок
    целиком, и агент молча переставал показывать расчёты;
  • любая правка формулировки означала тридцать четыре одинаковых диффа.

Теперь блок подмешивается в промпт В МОМЕНТ ИСПОЛНЕНИЯ (workflow_engine),
как и список методик. Инструкция шаблона снова про предметную область, а не
про разметку.

Держать синхронно с `COMPONENTS` в `frontend/js/agent_views.js`: имя,
которого нет во фронтенде, отрисуется обычным блоком кода. За этим следит
tests/test_agent_templates.py.
"""

from __future__ import annotations

# name -> когда брать. Порядок — от самого частого к редкому: модель читает
# список сверху вниз и первое подходящее чаще всего и берёт.
COMPONENTS: tuple[tuple[str, str], ...] = (
    ("calc_trace", "посчитал что-то — ОБЯЗАТЕЛЬНО, всегда: исходные данные, формула, шаги, результат, код"),
    ("verdict", "готов ответ по объекту: что сошлось, что нет, что исправить и на чём основано"),
    ("comparison", "сравниваешь варианты"),
    ("data_table", "больше трёх строк данных"),
    ("metric_cards", "2-6 ключевых чисел"),
    ("spec_sheet", "паспорт или спецификация: параметр — значение — источник"),
    ("chart", "зависимость или динамика"),
    ("checklist", "что проверить дальше"),
    ("timeline", "план или стадии"),
    ("source_list", "литература"),
    ("file_card", "сделал файл"),
    ("model_result", "результат модели коллектива — интерфейс рисует его сам из ответа run_model, "
                     "optimize_model и train_model; вручную не собирай"),
)

VERDICT_HINT = """\
Компонент verdict — заключение, а не пересказ. Его поля:
  status: ok | warn | fail — сводный итог;
  headline, summary — одной строкой, что решено и почему;
  checks: [{label, value, status, note}] — по строке на КАЖДЫЙ критерий,
    который проверялся, включая пройденные: инженеру нужно видеть, что
    проверено, а не только то, что не сошлось;
  fix: {text, label, action} — если status не ok. action — это готовый
    следующий вопрос тебе же: участник нажмёт кнопку, и вопрос придёт.
    Формулируй его как команду («Пересчитай на типоразмер 110 м² …»);
  sources: [{title, note, date, url}] — методика, ГОСТ, статья, база
    проекта. Пустой список честнее выдуманной ссылки."""


FILE_CARD_HINT = """\
Компонент file_card — только для файла, который ты СОЗДАЛ инструментом
(make_document и т.п.). Поля плоские, без вложенных объектов:
  {"component": "file_card", "title": "…", "filename": "…", "size": "40 КБ",
   "url": "/api/chat/attachments/att-…", "note": "что внутри"}
  url — поле «скачать» из результата инструмента, дословно. Без url кнопки
  «Скачать» не будет, и участник не сможет забрать файл.
  Для png (рисунки структур, графики) карточка показывает САМУ КАРТИНКУ
  в чате. Писать ссылку на вложение голым текстом или код-блоком нельзя —
  картинки на экране не будет, только адрес."""


def prompt_block() -> str:
    """Блок для системного промпта агента: чем показывать результат.

    Намеренно короткий: имя компонента и одна строка «когда брать». Полей
    компонента модель не видит и не должна — фронтенд игнорирует лишнее и
    подставляет умолчания, а перечисление всех полей десяти компонентов
    стоило бы тысячи токенов на каждом вопросе.
    """
    lines = [
        "## Чем показывать результат",
        "",
        "Не пересказывай числа текстом. После двух-трёх предложений "
        "человеческим языком добавь блок с данными — платформа отрисует "
        "его в рабочей области.",
        "",
        "ФОРМАТ СТРОГИЙ. Язык блока — всегда `aios-view`, а имя компонента "
        "идёт ВНУТРИ, полем \"component\". Языком блока имя компонента не "
        "бывает никогда:",
        "",
        "```aios-view",
        '{"component": "calc_trace", "title": "Площадь аппарата", '
        '"result": {"value": "92,4", "unit": "м²"}}',
        "```",
        "",
        "Неверно: ```calc_trace, ```json, ```verdict — такой блок останется "
        "просто текстом, и участник увидит сырой JSON вместо расчёта.",
        "",
        "Какой компонент брать:",
        "",
    ]
    width = max(len(name) for name, _ in COMPONENTS)
    for name, when in COMPONENTS:
        lines.append(f"  {name.ljust(width)}  — {when}")
    lines += ["", "Один ответ — один-два компонента.", "", VERDICT_HINT, "", FILE_CARD_HINT]
    return "\n".join(lines)


def names() -> tuple[str, ...]:
    return tuple(name for name, _ in COMPONENTS)
